function translate(text) {
  const language = $("#language")?.value || "English";
  if (language === "English") return text;
  const deleteProfile = text.match(/^Delete profile #(\d+)$/);
  if (deleteProfile && EXTRA_TRANSLATIONS[language]?.["Delete profile"]) {
    return `${EXTRA_TRANSLATIONS[language]["Delete profile"]} #${deleteProfile[1]}`;
  }
  const extraTranslation = EXTRA_TRANSLATIONS[language]?.[text];
  if (extraTranslation) return extraTranslation;
  const careerTranslation = CAREER_TRANSLATIONS[text]?.[["Kannada", "Tamil", "Malayalam", "Bengali", "Urdu"].indexOf(language)];
  if (careerTranslation) return careerTranslation;
  const additionalTranslation = ADDITIONAL_TRANSLATIONS[language]?.[text];
  if (additionalTranslation) return additionalTranslation;
  const matchCount = text.match(/^(\d+) pathways to explore$/);
  if (matchCount && ADDITIONAL_TRANSLATIONS[language]?.["pathways to explore"]) {
    return `${matchCount[1]} ${ADDITIONAL_TRANSLATIONS[language]["pathways to explore"]}`;
  }
  const matchScore = text.match(/^(\d+)% match$/);
  if (matchScore && ADDITIONAL_TRANSLATIONS[language]?.match) {
    return `${matchScore[1]}% ${ADDITIONAL_TRANSLATIONS[language].match}`;
  }
  const matchExplanation = text.match(/^Connects with (.*)\. Check official entry requirements before enrolling\.$/);
  if (matchExplanation && ADDITIONAL_TRANSLATIONS[language]?.["Connects with interests"]) {
    const interests = matchExplanation[1] === "your wider career exploration"
      ? ADDITIONAL_TRANSLATIONS[language]["your wider career exploration"]
      : matchExplanation[1].split(", ").map(translate).join(", ");
    return `${ADDITIONAL_TRANSLATIONS[language]["Connects with interests"]}: ${interests}. ${ADDITIONAL_TRANSLATIONS[language]["Check official entry requirements before enrolling."]}`;
  }
  const index = languageIndexes[language];
  if (index === null || index === undefined) return text;
  if (matchCount && UI_TRANSLATIONS["pathways to explore"]) return `${matchCount[1]} ${UI_TRANSLATIONS["pathways to explore"][index]}`;
  if (matchScore && UI_TRANSLATIONS.match) return `${matchScore[1]}% ${UI_TRANSLATIONS.match[index]}`;
  if (matchExplanation && UI_TRANSLATIONS["Connects with interests"]) {
    const interests = matchExplanation[1] === "your wider career exploration"
      ? (UI_TRANSLATIONS["your wider career exploration"][index] || UI_TRANSLATIONS["your wider career exploration"][0])
      : matchExplanation[1].split(", ").map((interest) => translate(interest)).join(", ");
    return `${UI_TRANSLATIONS["Connects with interests"][index] || UI_TRANSLATIONS["Connects with interests"][0]}: ${interests}. ${UI_TRANSLATIONS["Check official entry requirements before enrolling."][index] || UI_TRANSLATIONS["Check official entry requirements before enrolling."][0]}`;
  }
  const translated = UI_TRANSLATIONS[text]?.[index];
  return translated || text;
}

