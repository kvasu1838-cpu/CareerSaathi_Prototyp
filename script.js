function applyLanguage() {
  const language = $("#language").value;
  document.documentElement.lang = LANGUAGE_CODES[language] || "en";
  document.documentElement.dir = language === "Urdu" ? "rtl" : "ltr";
  document.title = translate("CareerSaathi | Career Counselling");
  const description = document.querySelector('meta[name="description"]');
  if (description) {
    const original = description.dataset.originalContent || description.content;
    description.dataset.originalContent = original;
    description.content = translate(original);
  }

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    const source = originalText.get(node) || "";
    const match = source.match(/^(\s*)(.*?)(\s*)$/s);
    if (!match) continue;
    const key = match[2].replace(/\s+/g, " ");
    node.nodeValue = `${match[1]}${translate(key)}${match[3]}`;
  }

  document.querySelectorAll("[placeholder], [aria-label], [title]").forEach((element) => {
    for (const attribute of ["placeholder", "aria-label", "title"]) {
      if (!element.hasAttribute(attribute)) continue;
      let originals = originalAttributes.get(element);
      if (!originals) {
        originals = {};
        originalAttributes.set(element, originals);
      }
      if (!(attribute in originals)) originals[attribute] = element.getAttribute(attribute);
      element.setAttribute(attribute, translate(originals[attribute]));
    }
  });

  document.querySelectorAll("[data-translation-source]").forEach((element) => {
    element.textContent = translate(element.dataset.translationSource);
  });

  if (currentRecommendations) renderRecommendations(currentRecommendations);
}

async function api(path, options = {}) {
  const response = await fetch(path, {
    ...options,
    headers: { "Content-Type": "application/json", ...(options.headers || {}) }
  });
  const data = await response.json().catch(() => ({}));
  if (!response.ok) throw new Error(typeof data.detail === "string" ? data.detail : (data.message || "Request failed. Check the server."));
  return data;
}
function esc(v="") {
  return String(v).replace(/[&<>"']/g, c => ({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]));
}
