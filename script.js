function status(el, text, error=false) {
  el.dataset.translationSource = text;
  el.textContent = translate(text);
  el.style.color = error ? "#ff9d9d" : "var(--teal)";
}

$("#assessmentForm").addEventListener("submit", async (event) => {
  event.preventDefault();
  const button = event.submitter;
  const state = $("#assessmentStatus");
  const p = profile();
  if (!p.interests.length) { status(state, "Please select at least one interest.", true); return; }
  if (button) button.disabled = true;
  status(state, "Finding suitable sample pathways...");
  try {
    await api("/api/profile", { method: "POST", body: JSON.stringify(p) });
    const result = await api("/api/recommendations", { method: "POST", body: JSON.stringify(p) });
    currentRecommendations = result;
    renderRecommendations(currentRecommendations);
    $("#recommendationSection").classList.remove("hidden");
    status(state, "Assessment saved. Your sample matches are ready.");
    $("#recommendationSection").scrollIntoView({ behavior: "smooth", block: "start" });
  } catch (e) { status(state, e.message, true); }
  finally { if (button) button.disabled = false; }
});

function addMessage(text, who) {
  const row = document.createElement("div");
  row.className = `message ${who === "user" ? "user" : "bot"}`;
  const p = document.createElement("p");
  p.textContent = text;
  row.append(p);
  $("#chatMessages").append(row);
  $("#chatMessages").scrollTop = $("#chatMessages").scrollHeight;
  return row;
}
async function sendChat(text) {
  text = text.trim();
  if (!text) return;
  addMessage(text, "user");
  const botRow = addMessage("", "bot");
  const turn = { message: text, botRow, requestId: 0 };
  chatTurns.push(turn);
  $("#chatMessage").value = "";
  $("#askButton").disabled = true;
  const language = $("#language").value || "English";
  const requestId = ++turn.requestId;
  try {
    const r = await api("/api/chat", { method: "POST", body: JSON.stringify({message:text, language}) });
    if (turn.requestId === requestId && language === $("#language").value) {
      botRow.querySelector("p").textContent = `${r.answer}\n\n${translate(r.disclaimer)}`;
    }
  } catch (e) {
    if (turn.requestId === requestId && language === $("#language").value) {
      botRow.querySelector("p").textContent = `${translate("Could not connect to the backend.")} ${translate(e.message)}`;
    }
  }
  finally { $("#askButton").disabled = false; $("#chatMessage").focus(); }
}
function refreshChatHistory() {
  const language = $("#language").value || "English";
  chatTurns.forEach(async turn => {
    const requestId = ++turn.requestId;
    try {
      const response = await api("/api/chat", {
        method: "POST",
        body: JSON.stringify({message:turn.message, language})
      });
      if (turn.requestId === requestId && language === $("#language").value) {
        turn.botRow.querySelector("p").textContent = `${response.answer}\n\n${translate(response.disclaimer)}`;
      }
    } catch (error) {
      if (turn.requestId === requestId && language === $("#language").value) {
        turn.botRow.querySelector("p").textContent = `${translate("Could not connect to the backend.")} ${translate(error.message)}`;
      }
    }
  });
}
